/**
 * npm run gen:api
 *   lib/api/schema/core.d.ts     ← /api/v1/openapi.json (Taimoor's spec, built from lib/taimoor/openapi.ts)
 *   lib/api/schema/huzaifa.d.ts  ← openapi/huzaifa.yaml
 *
 * Uses the running dev server for the core spec when it is up, otherwise
 * builds the same spec in-process with tsx.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'lib/api/schema');
fs.mkdirSync(outDir, { recursive: true });

const banner = (src) => `/* eslint-disable */\n// Generated by \`npm run gen:api\` from ${src}. Do not edit.\n\n`;

async function coreSpec() {
  const url = process.env.OPENAPI_URL ?? 'http://localhost:3000/api/v1/openapi.json';
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(3000) });
    if (res.ok) return { spec: await res.json(), src: url };
  } catch {
    // dev server not running
  }
  const json = execFileSync(
    process.execPath,
    [path.join(root, 'node_modules/tsx/dist/cli.mjs'), '-e', "import { buildOpenApiSpec } from './lib/taimoor/openapi'; process.stdout.write(JSON.stringify(buildOpenApiSpec('http://localhost:3000')))"],
    { cwd: root, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 },
  );
  return { spec: JSON.parse(json), src: 'lib/taimoor/openapi.ts (buildOpenApiSpec)' };
}

const core = await coreSpec();
fs.writeFileSync(path.join(outDir, 'core.d.ts'), banner(core.src) + astToString(await openapiTS(core.spec)));

const yamlUrl = pathToFileURL(path.join(root, 'openapi/huzaifa.yaml'));
fs.writeFileSync(path.join(outDir, 'huzaifa.d.ts'), banner('openapi/huzaifa.yaml') + astToString(await openapiTS(yamlUrl)));

console.log('Wrote lib/api/schema/core.d.ts and lib/api/schema/huzaifa.d.ts');
